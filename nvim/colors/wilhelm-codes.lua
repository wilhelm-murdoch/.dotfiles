-- wilhelm.codes, a Neovim colorscheme
--
-- Every colour is a token from assets/css/main.css. The palette below names
-- each token. Change the token first, then copy the value here.
--
-- The syntax rules follow assets/css/chroma.css. The scheme is monochrome
-- with one accent, and the tone gives the role:
--
--   text    names, punctuation, numbers and constants
--   soft    strings
--   muted   keywords and comments
--   dim     operators, line numbers and prompts
--   accent  functions, builtins, types, tags and sigil variables
--
-- The accent means live, current or mine. Nothing else may borrow it.
--
-- Install: copy this file to ~/.config/nvim/colors/ and run
--   :colorscheme wilhelm-codes

